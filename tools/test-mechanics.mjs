import assert from 'node:assert/strict';
globalThis.window = { addEventListener() {} };
const { Mechanics } = await import('../src/mechanics.js');
const { updateBiofeedback, biometricOverrides, mechanicsConfig } = await import('../src/mechanics.config.js');
const { makeFighter } = await import('../src/fighter.js');
const { bus } = await import('../src/eventBus.js');
const { createMatch, stepMatch } = await import('../src/game.js');
const t = Date.now();
const sample = (values = {}, time = t) => ({ t: time, hr: 80, breath: 10, stress: 0, calm: 1, source: 'mock', ...values });
const p = makeFighter(1, 200, 1); p.hp = 60;
updateBiofeedback(p, sample(), 1/60, t);
assert.equal(Mechanics.calcFlinchMultiplier(p), 0.8);
assert.equal(Mechanics.calcDamage(8, p, p), 7.36);
assert.equal(Mechanics.healTick(p, 1/60), 1.4/60);
assert.ok(Math.abs(Mechanics.meterGain(p, 'tick', 0) - 4.5/60) < 1e-10);
const stressed = makeFighter(2, 250, -1);
updateBiofeedback(stressed, sample({ hr:145, breath:27, stress:1, calm:0 }), 1/60, t);
assert.equal(Mechanics.calcFlinchMultiplier(stressed), 1.2);
assert.equal(Mechanics.calcDamage(8, p, stressed), 8.64);
assert.equal(Mechanics.healTick(stressed, 1/60), 0);
assert.equal(Mechanics.meterGain(stressed, 'hit_landed', 10), 0);
p.hp = 99.999;
assert.ok(Mechanics.healTick(p, 1/60) <= p.maxHp - p.hp);
p.meter = 99.99;
assert.ok(Mechanics.meterGain(p, 'hit_landed', 10) <= p.maxMeter - p.meter);
bus.emit('hit', { defender:1, t });
assert.equal(Mechanics.healTick(p, 1/60), 0, 'same-tick hit suppresses healing');
updateBiofeedback(p, sample(), 1/60, t + 4000);
assert.equal(Mechanics.calcDamage(8,p,p), 8);
assert.equal(Mechanics.meterGateOpen(p), false);
assert.equal(Mechanics.healTick(p, 1/60), 0);
for (const value of [NaN, Infinity, -Infinity]) {
  updateBiofeedback(p, sample({ hr:value }), 1/60, t);
  assert.equal(p.biofeedback.valid, false);
  assert.ok(Number.isFinite(Mechanics.calcDamage(8,p,p)));
}
const smooth = makeFighter(1,200,1);
updateBiofeedback(smooth, sample(), 1/60, t);
updateBiofeedback(smooth, sample({hr:120}, t+100), 1/60, t+100);
assert.equal(smooth.biofeedback.hr,100);
for(let i=0;i<20;i++) updateBiofeedback(smooth,sample({hr:120},t+100),1/60,t+100);
assert.equal(smooth.biofeedback.hr,100,'repeated physics reads do not add samples');
assert.equal(smooth.biofeedback.flinch,1.12,'HR spike increases flinch');
for(let i=2;i<=9;i++) updateBiofeedback(smooth,sample({hr:120},t+i*100),1/60,t+i*100);
assert.equal(smooth.biofeedback.hr,120);
assert.equal(smooth.biofeedback.gate,false);
const gate = makeFighter(1,200,1);
const saved = mechanicsConfig.smoothing.samples; mechanicsConfig.smoothing.samples = 1;
for(const [i,hr,expected] of [[0,109,true],[1,112,true],[2,114,false],[3,112,false],[4,110,true]]) {
  updateBiofeedback(gate,sample({hr},t+i*100),1/60,t+i*100);
  assert.equal(gate.biofeedback.gate,expected);
}
mechanicsConfig.smoothing.samples = saved;
biometricOverrides[1] = {hr:80,breath:10,stress:0,calm:1};
biometricOverrides[2] = {hr:145,breath:27,stress:1,calm:0};
const match=createMatch(); match.fighters[1].hp=match.fighters[2].hp=60;
let healed=0, meter=0, flinches=[];
bus.on('heal_tick', e=>{ assert.ok(e.amount>0); if(e.player===1) healed+=e.amount; });
bus.on('meter_gain', e=>{ if(e.player===1) meter+=e.amount; });
bus.on('flinch', e=>flinches.push(e));
for(let i=0;i<600;i++) stepMatch(match,1/60,t+i*1000/60);
assert.ok(Math.abs(match.fighters[1].hp-74)<1e-8);
assert.equal(match.fighters[2].hp,60);
assert.ok(Math.abs(match.fighters[1].meter-45)<1e-8);
assert.equal(match.fighters[2].meter,0);
assert.ok(Math.abs(healed-14)<1e-8);
assert.ok(Math.abs(meter-45)<1e-8);
match.fighters[1].x=300;match.fighters[2].x=350;
match.fighters[1].attack={kind:'light',elapsedMs:0,hasHit:false,phase:'active'};
stepMatch(match,1/60,t+10000);
assert.equal(flinches.length,1);
assert.equal(flinches[0].player,2);
assert.equal(flinches[0].magnitude,0.6);
assert.ok(Math.abs(match.fighters[2].hp-51.36)<1e-8);
biometricOverrides[1]=biometricOverrides[2]=null;
console.log('PASS: ten-second demo (+14 HP, +45 meter), damage/flinch, event amounts, caps, smoothing, spikes, hysteresis, stale/invalid samples, and post-hit heal delay.');
